#!/usr/bin/env python3
"""Windows 安装器（由 install.bat 调用）。

安装策略
--------
优先用**计划任务**：每 N 分钟拉起一次 ``tick``，进程跑完即退，空闲时
内存占用为 0。这是推荐方式。

若计划任务因权限等原因创建失败，退回**启动文件夹快捷方式 + daemon
常驻进程**：功能等价，但会常驻约 25 MB 内存。

全部提示信息由本脚本（UTF-8）输出，因此 .bat 里不需要写中文，
避免 cmd.exe 代码页导致的乱码。
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAIN = ROOT / "main.py"
CONFIG = ROOT / "config.json"
RECORD = ROOT / ".installed.json"

LOGO = "campus-netkeeper 校园网自动认证"


def _ok(msg: str) -> None:
    print(f"  [OK]   {msg}")


def _warn(msg: str) -> None:
    print(f"  [警告] {msg}")


def _fail(msg: str) -> None:
    print(f"  [失败] {msg}")


def _python_pair() -> tuple[str, str]:
    """返回 (python.exe, pythonw.exe)。"""
    exe = Path(sys.executable)
    windowless = exe.with_name("pythonw.exe")
    if not windowless.exists():
        windowless = exe
    return str(exe), str(windowless)


def _check_config() -> bool:
    if not CONFIG.exists():
        _fail(f"找不到配置文件 {CONFIG}")
        print("      请先双击 init.bat 完成初始化。")
        return False
    try:
        data = json.loads(CONFIG.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        _fail(f"配置文件无法解析：{exc}")
        return False
    if not str(data.get("username", "")).strip() or not str(data.get("password", "")):
        _fail("配置里还没有填写账号或密码")
        print("      请先双击 init.bat 完成初始化。")
        return False
    return True


def _run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    """执行外部命令。命令不可用时返回失败结果，不抛异常。

    某些企业策略会禁用 schtasks.exe；把这种情况当作"计划任务不可用"，
    走回退方案即可，没必要让整个安装失败。
    """
    try:
        return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                              errors="replace", **kwargs)
    except (OSError, subprocess.SubprocessError) as exc:
        return subprocess.CompletedProcess(cmd, 1, "", f"{type(exc).__name__}: {exc}")


def _short_path(path: str) -> str:
    """取 Windows 8.3 短路径（通常是纯 ASCII，可安全写入 .cmd）。"""
    if os.name != "nt":
        return path
    try:
        import ctypes
        from ctypes import wintypes

        func = ctypes.windll.kernel32.GetShortPathNameW
        func.argtypes = [wintypes.LPCWSTR, wintypes.LPWSTR, wintypes.DWORD]
        func.restype = wintypes.DWORD
        buffer = ctypes.create_unicode_buffer(1024)
        if func(str(path), buffer, 1024) and buffer.value:
            return buffer.value
    except (OSError, AttributeError):
        pass
    return str(path)


def _ascii_interpreter() -> str:
    """找一个"命令行里只含 ASCII"的 Python 启动方式。

    计划任务最终要靠 cmd.exe 执行批处理，而 cmd.exe 按系统 ANSI 代码页
    解释文件内容。只要写进文件的字符全为 ASCII，就永远不会因编码而出错，
    因此优先使用 ``py -3`` / ``python`` 这类纯 ASCII 命令。
    """
    for candidate in (["py", "-3"], ["python"]):
        result = _run([*candidate, "-c", "import sys"])
        if result.returncode == 0:
            return " ".join(candidate)
    return ""


def _make_tick_launcher(windowless: str) -> Path:
    """生成启动器批处理，供计划任务调用。

    设计要点：

    * 用 ``cd /d "%~dp0"`` 而不是硬编码项目路径 —— ``%~dp0`` 由 cmd.exe
      在运行时解析，文件内容里不需要出现任何中文，天然免疫编码问题。
    * 解释器优先选纯 ASCII 命令（``py -3`` / ``python``）。
    * 只有在都不可用时才写入绝对路径，并按系统 ANSI 代码页编码。
      **绝不用** ``ascii + errors=ignore``：那会把中文路径整段删掉，
      得到一个指向错误位置、静默失败的启动器。
    """
    launcher = ROOT / "_tick.cmd"
    interpreter = _ascii_interpreter()

    if interpreter:
        body = (
            "@echo off\r\n"
            "rem Auto-generated by campus-netkeeper installer. Do not edit.\r\n"
            'cd /d "%~dp0"\r\n'
            f"{interpreter} main.py tick --quiet\r\n"
        )
    else:
        body = (
            "@echo off\r\n"
            "rem Auto-generated by campus-netkeeper installer. Do not edit.\r\n"
            'cd /d "%~dp0"\r\n'
            f'"{_short_path(windowless)}" main.py tick --quiet\r\n'
        )

    try:
        launcher.write_bytes(body.encode("ascii"))
        return launcher
    except UnicodeEncodeError:
        pass
    for encoding in ("mbcs", "utf-8"):
        try:
            launcher.write_bytes(body.encode(encoding))
            return launcher
        except (UnicodeEncodeError, LookupError):
            continue
    launcher.write_bytes(body.encode("utf-8"))
    return launcher


def _schtasks(args: list[str]) -> subprocess.CompletedProcess:
    return _run(["schtasks", *args])


def _state_tick(path: Path) -> float:
    try:
        return float(json.loads(path.read_text(encoding="utf-8")).get("last_tick_at", 0))
    except (OSError, ValueError, TypeError):
        return 0.0


def _verify_task_runs(tasks: list[str]) -> bool:
    """实际触发一次任务，确认它真的跑起来了。

    计划任务能"创建成功"但实际不执行的情况不少（路径引号没处理好、
    解释器找不到等）。用状态文件的时间戳做端到端验证，比看返回码可靠。
    """
    import time

    state = ROOT / "state.json"
    before = _state_tick(state)
    _schtasks(["/Run", "/TN", tasks[0]])
    for _ in range(10):
        time.sleep(1.0)
        if _state_tick(state) > before:
            return True
    return False


def install_scheduled_tasks(interval_minutes: int) -> tuple[bool, list[str]]:
    """创建计划任务，返回 (是否成功, 已创建的任务名列表)。"""
    _, windowless = _python_pair()
    launcher = _make_tick_launcher(windowless)
    created: list[str] = []

    specs = [
        ("CampusNetkeeper-Logon", ["/SC", "ONLOGON"]),
        ("CampusNetkeeper-Tick", ["/SC", "MINUTE", "/MO", str(interval_minutes)]),
    ]

    for name, schedule in specs:
        result = _schtasks([
            "/Create", "/TN", name,
            "/TR", f'"{launcher}"',
            *schedule,
            "/RL", "LIMITED",
            "/F",
        ])
        if result.returncode != 0:
            _warn(f"创建计划任务 {name} 失败：{(result.stderr or result.stdout).strip()[:160]}")
            # 回滚已创建的，避免半途而废的状态
            for done in created:
                _schtasks(["/Delete", "/TN", done, "/F"])
            return False, []
        created.append(name)

    if not _verify_task_runs(created):
        _warn("计划任务已创建，但实际触发后没有产生执行记录")
        for done in created:
            _schtasks(["/Delete", "/TN", done, "/F"])
        return False, []

    return True, created


def install_startup_shortcut() -> bool:
    """回退方案：启动文件夹快捷方式 + daemon 常驻。"""
    _, windowless = _python_pair()
    script = r"""
$startup = [Environment]::GetFolderPath('Startup')
$link = Join-Path $startup 'Campus Netkeeper.lnk'
$shell = New-Object -ComObject WScript.Shell
$sc = $shell.CreateShortcut($link)
$sc.TargetPath = $env:NK_PYTHONW
$sc.Arguments = '"' + $env:NK_MAIN + '" daemon'
$sc.WorkingDirectory = $env:NK_ROOT
$sc.WindowStyle = 7
$sc.Description = 'Campus network auto login'
$sc.Save()
if (Test-Path $link) { Write-Output 'OK' } else { Write-Output 'FAIL' }
"""
    env = dict(os.environ)
    env.update({"NK_PYTHONW": windowless, "NK_MAIN": str(MAIN), "NK_ROOT": str(ROOT)})
    result = _run(
        ["powershell", "-NoProfile", "-NonInteractive", "-Command", script], env=env
    )
    return "OK" in (result.stdout or "")


def main() -> int:
    print("=" * 60)
    print(f"{LOGO} · Windows 安装")
    print("=" * 60)

    if not _check_config():
        return 2

    interval = 2
    try:
        raw = json.loads(CONFIG.read_text(encoding="utf-8-sig")).get("interval", 120)
        interval = max(1, min(10, int(raw) // 60 or 2))
    except (OSError, ValueError, TypeError):
        pass
    print(f"\n检测间隔：{interval} 分钟（由 config.json 的 interval 换算）\n")

    print("正在注册计划任务（推荐：空闲时内存占用为 0）…")
    ok, tasks = install_scheduled_tasks(interval)

    record = {"mode": "", "tasks": [], "root": str(ROOT), "interval": interval}

    if ok:
        _ok(f"已创建计划任务：{', '.join(tasks)}")
        record["mode"] = "scheduled_task"
        record["tasks"] = tasks
        print("\n  -> 登录 Windows 时自动运行一次，之后每"
              f" {interval} 分钟检测一次。")
        print("  -> 每次执行约 1 秒，执行完即退出，不常驻内存。")
    else:
        print("\n计划任务不可用，改用回退方案…")
        if install_startup_shortcut():
            _ok("已在启动文件夹创建快捷方式（daemon 常驻模式）")
            record["mode"] = "startup_daemon"
            print("\n  -> 登录 Windows 后自动常驻运行。")
            print("  -> 注意：该模式常驻约 25 MB 内存。")
        else:
            _fail("两种方式都失败了")
            print("\n可以手动安装：把下面这条命令加到「任务计划程序」或启动项里")
            _, windowless = _python_pair()
            print(f'  "{windowless}" "{MAIN}" tick --quiet')
            return 1

    RECORD.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\n" + "-" * 60)
    print("验证：双击 check_status.bat 查看当前状态；")
    print("      双击 view_log.bat 查看运行日志；")
    print("      双击 uninstall.bat 可完整卸载。")
    print("-" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
